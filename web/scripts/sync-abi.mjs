// Copies ABIs from the Foundry build (../contracts/out) into src/abi as typed TS constants,
// and the local deployment address into .env.local if present.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const out = path.resolve(root, "../contracts/out");
for (const name of ["Launchpad", "Pool", "LaunchToken"]) {
  const json = JSON.parse(fs.readFileSync(path.join(out, `${name}.sol`, `${name}.json`), "utf8"));
  const ts = `// Generated by scripts/sync-abi.mjs. Do not edit.\nexport const ${name[0].toLowerCase() + name.slice(1)}Abi = ${JSON.stringify(json.abi, null, 2)} as const;\n`;
  fs.writeFileSync(path.join(root, "src/abi", `${name}.ts`), ts);
  console.log("wrote", name);
}
